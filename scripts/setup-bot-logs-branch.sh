#!/usr/bin/env bash
# setup-bot-logs-branch.sh — creates the orphan bot-logs branch that
# github-log-shipper.ts will push to. Run once locally, then push.
#
# Why an orphan branch? So log commits don't pollute main's history.
# The bot-logs branch lives entirely separate from main — it can be
# deleted and recreated at any time without affecting the codebase.
#
# Usage:
#   ./setup-bot-logs-branch.sh
#   # or override defaults:
#   BRANCH=bot-logs REMOTE=origin ./setup-bot-logs-branch.sh

set -euo pipefail

BRANCH="${BRANCH:-bot-logs}"
REMOTE="${REMOTE:-origin}"

if ! git rev-parse --git-dir >/dev/null 2>&1; then
  echo "❌ Not in a git repository. cd to your repo and re-run."
  exit 1
fi

# Check if the branch already exists (locally or remote)
if git show-ref --verify --quiet "refs/heads/${BRANCH}" 2>/dev/null; then
  echo "✓ Branch '${BRANCH}' already exists locally. Nothing to do."
  exit 0
fi

if git show-ref --verify --quiet "refs/remotes/${REMOTE}/${BRANCH}" 2>/dev/null; then
  echo "✓ Branch '${BRANCH}' already exists on ${REMOTE}. Nothing to do."
  exit 0
fi

echo "→ Creating orphan branch '${BRANCH}'..."

# Save current branch to restore later
CURRENT_BRANCH="$(git symbolic-ref --short HEAD 2>/dev/null || echo '')"

# Create orphan branch
git checkout --orphan "${BRANCH}"

# Remove all tracked files from the index (working tree untouched after we restore)
git rm -rf . >/dev/null 2>&1 || true

# Create a README so the branch isn't empty
cat > README.md <<EOF
# Bot Logs

This branch is auto-populated by \`github-log-shipper.ts\` running inside
the MathU bot. Each push creates timestamped log files under
\`logs/<date>/<basename>-<timestamp>.log\`.

This is an **orphan branch** — its history is separate from \`main\`.
You can delete and recreate it freely:

\`\`\`bash
git push origin --delete ${BRANCH}
./setup-bot-logs-branch.sh
\`\`\`

## Browsing logs

- Browse: https://github.com/<owner>/<repo>/tree/${BRANCH}/logs
- Or clone just this branch: \`git clone --branch ${BRANCH} --single-branch <repo-url>\`
EOF

git add README.md
git commit -m "init ${BRANCH} branch (auto-generated by setup-bot-logs-branch.sh)" \
  --author="MathU Bot <bot@mathu.local>"

echo "→ Pushing to ${REMOTE}/${BRANCH}..."
git push "${REMOTE}" "${BRANCH}"

# Restore original branch
if [ -n "${CURRENT_BRANCH}" ]; then
  echo "→ Restoring original branch '${CURRENT_BRANCH}'..."
  git checkout "${CURRENT_BRANCH}" 2>/dev/null || true
fi

echo ""
echo "✅ Done. Branch '${BRANCH}' created and pushed."
echo ""
echo "Next: add a GitHub PAT with 'Contents: write' permission as a repo"
echo "secret named GITHUB_LOGS_TOKEN, then restart the bot."
